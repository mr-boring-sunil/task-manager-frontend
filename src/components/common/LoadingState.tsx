import React from 'react';
import { Loader2 } from 'lucide-react';

interface LoadingStateProps {
  message?: string;
  size?: 'sm' | 'md' | 'lg';
  className?: string;
}

export const LoadingState: React.FC<LoadingStateProps> = ({
  message = 'Loading system telemetry...',
  size = 'md',
  className = '',
}) => {
  const iconSizes = {
    sm: 'w-4 h-4',
    md: 'w-6 h-6',
    lg: 'w-8 h-8',
  };

  return (
    <div className={`flex flex-col items-center justify-center p-8 text-slate-400 ${className}`}>
      <Loader2 className={`${iconSizes[size]} animate-spin text-rose-500 mb-2`} />
      <p className="text-xs font-mono uppercase tracking-wider">{message}</p>
    </div>
  );
};
